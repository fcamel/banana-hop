'use strict';
const assert=require('node:assert/strict');
const {createEnvironment}=require('../sim/environment.cjs');
const {encode}=require('../sim/training.cjs');
const {skillContext}=require('../sim/skills.cjs');
const {mirrorFeatures,mirrorContext,mirrorChoice,mirrorDirection,totalVariation}=require('../sim/mirror-audit.cjs');
const o=createEnvironment({seed:1,mode:'milk',survivalOnly:true,entrance:false,width:1000,height:650,mobile:false}).observe();
Object.assign(o.player,{x:100,y:25,recoilX:13,padDriftX:-9});
o.enemies=[{id:1,type:'slice',x:140,y:40,z:20,stackCount:1},{id:2,type:'milk',x:80,y:60,z:0,milkAim:.7,milkPhase:'aim'}];
o.milkDrops=[{x:120,y:55,z:32,vx:-70,vy:11,life:2,hostile:true}];o.milkBottles=[{id:3,x:70,y:50}];o.pickups=[{id:4,x:50,y:30}];o.surfPickups=[{id:5,x:130,y:45}];o.spawnWarnings=[{x:90,y:40,time:.4}];
const m=JSON.parse(JSON.stringify(o));
for(const e of [m.player,...m.enemies,...m.milkDrops,...m.milkBottles,...m.pickups,...m.surfPickups,...m.spawnWarnings])e.x=-e.x;
m.player.recoilX=-m.player.recoilX;m.player.padDriftX=-m.player.padDriftX;m.enemies[1].milkAim=Math.PI-m.enemies[1].milkAim;m.milkDrops[0].vx=-m.milkDrops[0].vx;
const h={get:()=>({vx:23,vy:-7,vz:4,valid:true})},mh={get:()=>({vx:-23,vy:-7,vz:4,valid:true})};
const active={skill:2,frames:12,travel:0,direction:2,triggered:true,airborne:true,target:{x:140,y:40}},ma={...active,direction:4,target:{x:-140,y:40}};
const f=encode(o,[2,1,0,0],h,active),before=Array.from(f),expected=encode(m,[4,1,0,0],mh,ma),mirrored=mirrorFeatures(f);
for(let i=0;i<f.length;i++)assert.ok(Math.abs(mirrored[i]-expected[i])<1e-12,`feature ${i}`);
assert.deepEqual(Array.from(f),before);assert.deepEqual(Array.from(mirrorFeatures(mirrored)),before);
assert.deepEqual(mirrorContext(skillContext(o)),skillContext(m));
for(let d=0;d<9;d++)assert.deepEqual(mirrorChoice(mirrorChoice([3,d,0,0])),[3,d,0,0]);
const a=Array(9).fill(0);a[1]=1;const b=mirrorDirection.map(i=>a[i]);assert.equal(totalVariation(a,mirrorDirection.map(i=>b[i])),0);assert.equal(totalVariation(a,b),1);
assert.throws(()=>mirrorFeatures([]));console.log('Mirror audit tests passed');
