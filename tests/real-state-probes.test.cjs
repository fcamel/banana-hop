'use strict';
const assert=require('node:assert/strict');
const {skillEnvironment,featureCount}=require('../sim/training.cjs');
const {createNetwork,Random}=require('../sim/ppo.cjs');
const {input}=require('../sim/skill-semantic-probes.cjs');
const audit=require('../sim/real-state-probes.cjs');
const e=skillEnvironment({seed:1,width:1000,height:650,mobile:false});e.step([3,1,0,0]);
const f=e.features(),active=e.diagnosticOption(),copy=JSON.stringify(active);
assert.ok(active);assert.deepEqual(Array.from(audit.features(e.observe(),audit.previousFrom(f),e.motion(),active)),Array.from(f));
active.frames=999;assert.notEqual(e.diagnosticOption().frames,999);
const o=input({family:'distance',phase:'ground',bearing:0,time:5,distance:60,height:0}).observation;
o.enemies.push({...o.enemies[0],id:2,x:80});
const original=JSON.stringify(o),variants=audit.variants(o,1),near=variants.find(v=>v.label==='0.5').observation,far=variants.find(v=>v.label==='1.5').observation;
const net=createNetwork(featureCount,4,new Random(1));net.parameters.fill(0);
const a=audit.predict(net,near,[0,0,0,0],null,null),b=audit.predict(net,far,[0,0,0,0],null,null);
assert.equal(a.targetSlotIdentities[1],'slice:1');assert.equal(b.targetSlotIdentities[1],'slice:2');
assert.ok(Math.abs(Object.values(a.joint).reduce((s,p)=>s+p,0)-1)<1e-12);
assert.ok(audit.tv(a.joint,b.joint)<1e-12,'Uniform target probabilities must compare by identity, not sorted slot');
assert.equal(JSON.stringify(o),original);assert.deepEqual(near.enemies[1],o.enemies[1]);
assert.equal(audit.compare(a,a).jointTV,0);
assert.equal(variants.filter(v=>v.family==='player-phase').length,0);
const oldState=e.diagnosticDigest();audit.predict(net,e.observe(),audit.previousFrom(f),e.motion(),e.diagnosticOption());assert.equal(e.diagnosticDigest(),oldState);assert.equal(JSON.stringify(e.diagnosticOption()),copy);
console.log('Real state probe tests passed');
